RANGE_TEST = "tests/pytests/test_cuest_jk.py"
JK_SHA = "652085d760ee0a790fff4f02a354775eeb311ca5a941e88e66b18b75282cbffe"
RANGE_SHA = "881ad935c4a7f13dedd696c0a5b3c0c3e677a78fe5a967dd1d86177197db412c"
PINS = dict(baseline=BASE, candidate=CANDIDATE)
ORIGINS = dict(baseline=p.BASE, candidate=p.OBSERVED_CANDIDATE)


def proof(sources):
    """Exact Git patch, immediate ancestry, whole test file, and A/B delta proof."""
    root = sources["candidate"]

    def git(*args):
        return subprocess.check_output(["git", "-C", str(root), *args])

    patches = []
    for arm, pin in PINS.items():
        p.require(git("rev-parse", pin+"^").decode().strip() == ORIGINS[arm],
                  "common fix must directly extend original arm")
        p.require(git("diff", "--name-only", ORIGINS[arm], pin).decode().splitlines() == [JK],
                  "shared fix must touch only generic JK")
        patches.append(git("diff", "--binary", ORIGINS[arm], pin))
        for file, expected in [(JK, JK_SHA), (RANGE_TEST, RANGE_SHA)]:
            p.require(hashlib.sha256(git("show", pin+":"+file)).hexdigest() == expected,
                      "shared JK or unchanged original range test hash")
        p.require(git("show", ORIGINS[arm]+":"+RANGE_TEST) == git("show", pin+":"+RANGE_TEST),
                  "original range test modified")
        p.check_source(sources[arm], pin)
    old = git("diff", "--binary", p.BASE, p.OBSERVED_CANDIDATE)
    new = git("diff", "--binary", BASE, CANDIDATE)
    p.require(patches[0] == patches[1], "shared patches differ")
    p.require(old == new and set(git("diff", "--name-only", BASE, CANDIDATE).decode().splitlines()) == p.OWNED_DIFF,
              "original five-path optimization diff changed")
    return dict(origins=ORIGINS, pins=PINS, jk_sha256=JK_SHA, range_test_sha256=RANGE_SHA,
                shared_patch_sha256=hashlib.sha256(patches[0]).hexdigest(),
                optimization_diff_sha256=hashlib.sha256(new).hexdigest())


def validate(m):
    p.require(m["build_mode"] == MODE and "artifact_pair" not in m,
              "fresh common-fixed cohort forbids artifact adoption")
    p.require(m["build_budget_seconds"] == [3600, 3600] and
              m["test_smoke_budget_seconds"] == 1800 and m["production_budget_seconds"] == 3600 and
              m["per_process_timeout_seconds"] == 600, "fresh build budget policy")
    p.require(m["approval"]["review_id"] == REVIEW_ID, "shared fix parent review identity")
    for arm, item in m["arms"].items():
        p.require(item["pin"] == PINS[arm], "common-fixed source pin")
        for file, expected in [(JK, JK_SHA), (RANGE_TEST, RANGE_SHA)]:
            p.require(item["files"][file]["sha256"] == expected, "shared fix/original test manifest")
    value = m["shared_fix"]
    p.require(value["origins"] == ORIGINS and value["pins"] == PINS and
              value["jk_sha256"] == JK_SHA and value["range_test_sha256"] == RANGE_SHA,
              "shared fix proof identity")
    for key in ("shared_patch_sha256", "optimization_diff_sha256"):
        p.require(value[key] == EXPECTED_PROOF[key], "shared fix patch/delta proof")


