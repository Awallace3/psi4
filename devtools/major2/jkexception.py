import policy as p

MODE = "fresh-jkexception"
REVIEW_ID = "parent-shared-jkexception-review-required"
BASE = "c56708fc6f6e8fcf2801868f0d3cb49bdb1bb0a2"
CANDIDATE = "c9c266e5a383c962f9a4c8449dfbc54aeafaf6f2"
RUN = p.P + "/runs/saptdft-cuest-cpks/major2-jkexception-20261018"
HARNESS = p.P + "/gits/psi4.saptdft-cuest-major2-jkexception-20261018"
SOURCES = {
    arm: p.P + "/gits/psi4.saptdft-cuest-major2-jkexception-" + arm + "-20261018"
    for arm in ("baseline", "candidate")
}
BUILD = "build_major2_cuda_jkexception"
